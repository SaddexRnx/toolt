const DICTS: Record<Lang, Dict> = {
  en,
  es,
  fr,
  de,
  it,
  pt,
  nl,
  ru,
  zh,
  ja,
  ko,
  ar,
  tr,
  pl,
  hi,
  vi,
  id,
  uk,
  sv,
  cs,
  he,
};

type I18nContextValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  dir: "ltr" | "rtl";
};

const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}

type PluralForm = "zero" | "one" | "two" | "few" | "many" | "other";

/**
 * Plural category for a count. Arabic needs all six forms; Russian,
 * Ukrainian, Polish and Czech distinguish one/few/many; the rest of the
 * languages here only need one/other.
 */
function pluralForm(lang: Lang, n: number): PluralForm {
  const mod10 = n % 10;
  const mod100 = n % 100;
  switch (lang) {
    case "ar":
      if (n === 0) return "zero";
      if (n === 1) return "one";
      if (n === 2) return "two";
      if (mod100 >= 3 && mod100 <= 10) return "few";
      if (mod100 >= 11) return "many";
      return "other";
    case "ru":
    case "uk":
      if (mod10 === 1 && mod100 !== 11) return "one";
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few";
      return "many";
    case "pl":
      if (n === 1) return "one";
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few";
      return "many";
    case "cs":
      if (n === 1) return "one";
      if (n >= 2 && n <= 4) return "few";
      return "other";
    default:
      return n === 1 ? "one" : "other";
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  // Always start from EN on both server and client to avoid hydration mismatch.
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const restore = () => {
      try {
        const saved = localStorage.getItem("toolt.lang") as Lang | null;
        if (saved && DICTS[saved]) {
          setLangState(saved);
          return;
        }
        const nav = (navigator.language || "en").slice(0, 2).toLowerCase() as Lang;
        if (DICTS[nav]) setLangState(nav);
      } catch {
        /* ignore */
      }
    };
    // Defer the first read to a task: keeps the effect body free of
    // synchronous setState and matches the EN-first hydration contract.
    const id = window.setTimeout(restore, 0);
    return () => window.clearTimeout(id);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("toolt.lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  const dir: "ltr" | "rtl" = LANGUAGES.find((l) => l.code === lang)?.rtl ? "rtl" : "ltr";

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    // The pre-hydration script hides the body for non-English locales. Reveal
    // it only once React is rendering the same language the visitor expects,
    // so the server-rendered English text never flashes on screen.
    if (document.documentElement.getAttribute("data-boot-lang") === lang) {
      document.documentElement.classList.remove("i18n-boot");
    }
  }, [lang, dir]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const dict = DICTS[lang] || en;
      const count = typeof vars?.n === "number" ? vars.n : undefined;
      let template: string | undefined;

      if (count !== undefined) {
        const form = pluralForm(lang, count);
        template = dict[`${key}.${form}`] ?? en[`${key}.${form}`];
        if (!template) {
          template =
            (form === "one" ? (dict[key] ?? en[key]) : undefined) ??
            dict[`${key}.other`] ??
            en[`${key}.other`] ??
            dict[`${key}.plural`] ??
            en[`${key}.plural`] ??
            dict[key] ??
            en[key];
        }
      }

      template ??= dict[key] ?? en[key] ?? key;
      return interpolate(template, vars);
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t, dir }), [lang, setLang, t, dir]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}

export function useT() {
  return useI18n().t;
}

/**
 * Category names live in the tool catalog in English. This translates them
 * for display and falls back to the original name if a locale is missing.
 */
export function useCategoryLabel() {
  const { t } = useI18n();
  return useCallback(
    (category: string) => {
      if (!category) return "";
      if (category === "All") return t("catalog.category.all");
      const key = `category.${category.toLowerCase()}`;
      const label = t(key);
      return label === key ? category : label;
    },
    [t],
  );
}

